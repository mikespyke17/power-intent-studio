"""UPF -> design mapping, on the bundled aura_top example.

THE USE CASE (explicit request): load the aura_top RTL + LIB, map the
UPF already in examples/aura_top/upf/, and check the mapping is right.
Both UPFs were generated by this app from examples/aura_top/aura_top.pis,
so mapping one back onto the same design must reproduce that project.
Every diagram state family is compared field by field, by NAME (ids
differ between two loads).

- The LEGACY file (port states + legacy PST) carries everything the
  project holds, so it must match 100% with zero diagnostics.
- The MODERN file (supply-set states + power state group) cannot carry
  three things, by the format the generator writes, not by an import
  gap: per-supply state NAMES, and the states (and PST column) of a
  supply no supply set uses -- here VDD_HI, which only feeds a switch.
  Those differences are asserted EXACTLY, so anything else that differs
  still fails.

Runs the real pipeline the app runs: filelist -> elaborate_rtl ->
elaborate_power_intent -> run_mapping -> import_power_intent.
"""

from __future__ import annotations

import glob
from pathlib import Path

import pytest

from frontend.src.app.project_file import deserialize_project

EXAMPLE = Path(__file__).resolve().parents[2] / "examples" / "aura_top"


@pytest.fixture(scope="module")
def designs():
    """(backend Design, adapted Design) for aura_top, from its own filelist
    and the TT .lib -- exactly the README quickstart's inputs."""
    from backend.api import elaborate_rtl
    from frontend.src.backend_integration.backend_adapter import adapt_design
    from frontend.src.hierarchy_view.filelist import parse_filelist

    filelist = parse_filelist(str(EXAMPLE / "filelist.f"))
    libs = sorted(glob.glob(str(EXAMPLE / "lib" / "lib" / "*tt*.lib")))
    real = elaborate_rtl(filelist.files, libs, top="aura_top", include_dirs=filelist.include_dirs)
    return real, adapt_design(real)


@pytest.fixture(scope="module")
def reference():
    return deserialize_project((EXAMPLE / "aura_top.pis").read_bytes())


def _map(designs, variant: str):
    from backend.api import elaborate_power_intent, run_mapping
    from frontend.src.backend_integration.backend_adapter import adapt_mapped_design, adapt_power_intent
    from frontend.src.power_intent_view.power_intent_import import import_power_intent

    real_rtl, rtl = designs
    path = str(EXAMPLE / "upf" / f"aura_top.{variant}.upf")
    power_intent = elaborate_power_intent(path, "upf")
    adapted = adapt_power_intent(power_intent)
    mapped = adapt_mapped_design(run_mapping(power_intent, real_rtl), adapted, rtl)
    return import_power_intent(adapted, rtl, mapped, path)


def snapshot(supply, domain, retention, switch, isolation, level_shifter, port_attribute, pst, macro) -> dict:
    """Every diagram family, keyed by names and paths instead of ids."""
    sets = {s.id: s.name for s in domain.supply_sets.values()}
    domains = {d.id: d.name for d in domain.domains.values()}
    places = {**supply.supply_port_placements, **supply.pg_pin_placements}
    nets = {p.id: p.name for p in supply.supply_port_placements.values()}
    switch_names = {s.id: s.name for s in switch.switches.values()}

    def where(key: str) -> str:
        placement = places.get(key)
        if placement is not None:
            return f"{placement.owner_path}/{placement.name}"
        if key.startswith("pg:"):
            _, path, pin = key.split(":", 2)
            return f"{path}/{pin}"
        if key.startswith("switch:"):
            _, switch_id, target = key.split(":", 2)
            target_placement = places.get(target)
            target_name = f"{target_placement.owner_path}/{target_placement.name}" if target_placement else target
            return f"switch-in {switch_names.get(switch_id, switch_id)} -> {target_name}"
        return f"?{key}"

    return {
        "supplies": sorted(
            (p.name, p.owner_path, p.is_internal_supply, p.is_virtual_supply, p.direction,
             tuple((s.state_type, s.voltage or "", s.name or "") for s in p.states))
            for p in supply.supply_port_placements.values()
        ),
        "connectors": sorted(tuple(sorted((where(a), where(b)))) for a, b in supply.supply_connector_placements),
        "supply_sets": sorted(
            (s.name, s.power, s.ground, s.n_well, s.p_well, tuple(sorted(s.owner_paths)))
            for s in domain.supply_sets.values()
        ),
        "domains": sorted(
            (d.name, tuple(sorted(d.owner_paths)), sets.get(d.primary_supply_set),
             tuple(sorted(sets.get(i, i) for i in d.secondary_supply_sets)))
            for d in domain.domains.values()
        ),
        "retention": sorted(
            (r.name, domains.get(r.power_domain_id), sets.get(r.primary_supply_set_id),
             sets.get(r.retention_supply_set_id), r.save_logic, r.restore_logic, tuple(sorted(r.elements)),
             r.owner_path)
            for r in retention.strategies.values()
        ),
        "switches": sorted(
            (s.name, domains.get(s.power_domain_id), s.input_supply_port, s.output_supply_port, s.control_port,
             s.control_signal, s.ack_port, s.ack_signal, s.on_state, s.off_state, s.cell_type,
             tuple(sorted(where(t) for t in s.target_ids)))
            for s in switch.switches.values()
        ),
        "isolation": sorted(
            (i.name, domains.get(i.power_domain_id), sets.get(i.isolation_supply_set_id),
             sets.get(i.source_supply_set_id), sets.get(i.sink_supply_set_id), i.clamp_value, i.isolation_control,
             i.isolation_sense, i.location, i.applies_to, tuple(sorted(i.elements)), i.name_prefix, i.owner_path)
            for i in isolation.strategies.values()
        ),
        "level_shifters": sorted(
            (l.name, domains.get(l.power_domain_id), l.applies_to, l.rule, l.location, str(l.threshold),
             tuple(sorted(l.elements)), l.name_prefix, l.cell_type)
            for l in level_shifter.strategies.values()
        ),
        "port_attributes": sorted((k, sets.get(v, v)) for k, v in port_attribute.assignments.items()),
        "power_state_table": sorted(
            (r.state_name, domains.get(r.power_domain_id),
             tuple(sorted((nets.get(n, n), v) for n, v in r.net_states.items())))
            for r in pst.rows.values()
        ),
        "macro_attachments": sorted(macro.attachments),
    }


def _expected(reference) -> dict:
    r = reference
    return snapshot(r.supply_state, r.domain_state, r.retention_state, r.power_switch_state, r.isolation_state,
                    r.level_shifter_state, r.port_attribute_state, r.power_state_table_state,
                    r.macro_power_intent_state)


def _got(imported) -> dict:
    i = imported
    return snapshot(i.supply, i.domain, i.retention, i.power_switch, i.isolation, i.level_shifter,
                    i.port_attribute, i.power_state_table, i.macro_power_intent)


FAMILIES = ["supplies", "connectors", "supply_sets", "domains", "retention", "switches", "isolation",
            "level_shifters", "port_attributes", "power_state_table", "macro_attachments"]


# --- legacy: everything the project holds, 100% ---------------------------


@pytest.fixture(scope="module")
def legacy(designs):
    return _map(designs, "legacy")


def test_the_legacy_upf_maps_with_no_diagnostics(legacy):
    assert [(d.severity.name, d.message) for d in legacy.diagnostics] == []


@pytest.mark.parametrize("family", FAMILIES)
def test_the_legacy_upf_reproduces_the_project(legacy, reference, family):
    assert _got(legacy)[family] == _expected(reference)[family]


# --- modern: everything the format carries ---------------------------------


@pytest.fixture(scope="module")
def modern(designs):
    return _map(designs, "modern")


def test_the_modern_upf_maps_with_no_diagnostics(modern):
    assert [(d.severity.name, d.message) for d in modern.diagnostics] == []


def _without_state_names(supplies):
    return sorted((*s[:5], tuple((t, v, "") for t, v, _ in s[5])) for s in supplies)


@pytest.mark.parametrize("family", [f for f in FAMILIES if f not in ("supplies", "power_state_table")])
def test_the_modern_upf_reproduces_the_project(modern, reference, family):
    assert _got(modern)[family] == _expected(reference)[family]


def test_the_modern_upf_supplies_differ_only_by_what_it_cannot_carry(modern, reference):
    """Per-supply state names are not in a modern file at all, and VDD_HI
    -- in no supply set -- has no supply-set state to carry its states."""
    expected = _without_state_names(_expected(reference)["supplies"])
    expected = [s if s[0] != "VDD_HI" else (*s[:5], ()) for s in expected]
    assert _got(modern)["supplies"] == expected


def test_the_modern_upf_power_state_table_differs_only_by_vdd_hi(modern, reference):
    """Every row and every other cell matches; only VDD_HI's column is
    absent, for the same reason as its states."""
    expected = [
        (name, domain, tuple(cell for cell in cells if cell[0] != "VDD_HI"))
        for name, domain, cells in _expected(reference)["power_state_table"]
    ]
    assert _got(modern)["power_state_table"] == expected
